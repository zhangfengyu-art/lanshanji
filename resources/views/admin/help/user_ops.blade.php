<div class="box box-info">
    <div class="box-header with-border">
        <h3 class="box-title">用户管理安全操作说明</h3>
    </div>
    <div class="box-body">
        <h4>一、第二阶段功能（已上线）</h4>
        <ul>
            <li>账号状态：可在用户列表快速启用/停用账号。</li>
            <li>邮箱验证：可在用户列表快速切换验证状态。</li>
            <li>停用生效：被停用账号无法登录，已登录会在后续请求中被拦截。</li>
        </ul>

        <h4>二、第三阶段功能（已上线）</h4>
        <ul>
            <li>登录风控：同一账号连续失败达到 5 次将触发临时锁定（10 分钟）。</li>
            <li>强制下线：点击“强制下线”会让目标用户所有会话失效。</li>
            <li>重置密码：可手输新密码或留空自动生成随机密码（会同时使旧会话失效）。</li>
            <li>批量启停：勾选用户后可执行批量启用/批量停用。</li>
            <li>分组标签：可在编辑页维护“用户分组”和“用户标签”，并在列表筛选。</li>
            <li>审计日志：关键动作可在“用户操作审计日志”页面追踪。</li>
        </ul>

        <h4>三、操作建议</h4>
        <ul>
            <li>高风险场景优先使用“强制下线 + 重置密码”组合。</li>
            <li>批量停用前先使用筛选确认范围，避免误伤正常用户。</li>
            <li>定期检查审计日志中异常高频失败登录和批量操作记录。</li>
        </ul>
    </div>
</div>
