        <p>中国大陆海关的相关规定是，邮寄包裹要收取“行邮税”，税金大于人民币50元需要收取，不超50元免收，而烟草商品的税率是50%，所以价值不满100元免收此项税费，但请注意不是指某1件商品单独的价格，是包裹内全部商品一起算。</p>
