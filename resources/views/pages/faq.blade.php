        <p>包裹在到达中国国内后，海关、邮政分别会向收件人发送短信，届时收件人可按收到的短信指引缴纳税费（邮政渠道缴税据说有额外费用），购买时请务必真实填写姓名与手机号，跨国包裹收件人姓名使用假名会导致包裹退运/丢失/销毁、无法顺利向海关缴纳税费等后果。如果收件人相关信息填写有误，请在发货前及时向本站反馈，EMS发货后无法再修改包裹的收件人信息。</p>
