        <p>EMS自缴税订单，在包裹内放有一张准确的购物凭据（购物明细书），多数情况下不需要您自己申报，但确也有少数地区海关喜欢让收件人再申报一遍。该购物凭据发货后会自动在订单详情页面右上角提供，您若需要可自行下载（顺丰含税包邮无此凭据提供）。</p>
