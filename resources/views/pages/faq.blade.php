        <p>因个别地区可能不认可价格排除其它费用，如果您完全不了解您当地海关情况，建议商品价格不超过1500人民币最为稳妥。</p>
        <p>包裹到达中国国内后，中国国内运输包裹内香烟、加热烟、雪茄合计不允许超过400支、烟丝不允许超过5kg（请阅读完本章节！存在特殊情况！），包裹内可以同时包含香烟、加热烟、雪茄、烟丝。</p>
