        <h4 class="faq-section-title">二、关于中国海关、包裹征税</h4>
        <p class="policy-disclaimer">注意：本部分内容来自中国公开的法规，以及根据社交媒体网友经历总结，仅供顾客参考，具体情况以实际为准。如果政策有变化不是本店能够决定的，也未必能及时总结更新内容，通关相关风险是由收件人自行承担。</p>

        <h5 class="faq-subtitle">1、会被海关征税么</h5>
        <p>中国大陆海关的相关规定是，邮寄包裹要收取「行邮税」，税金大于人民币 50 元需要收取，不超 50 元免收，而烟草商品的税率是 50%，所以价值不满 100 元免收此项税费，但请注意不是指某 1 件商品单独的价格，是包裹内全部商品一起算。</p>
        <p>购买商品支付的金额虽然包含了商品价格、服务费、运费、手续费等费用，但通常只有商品价格对应的金额需要缴纳「行邮税」。中国大陆相关法规里没有明确商品价格以外的费用（例如运费）是否也应被征税，社交媒体上网友分享的普遍经验是只按商品价格征税，但请注意实际尺度由您当地海关掌握，个别地区海关只认可排除运费，极个别地区海关连运费都不让排除。</p>
        <p>如果海关要求收件人「补充申报」，本店作为日本商店，没有体验过中国海关申报填写流程，无法为您提供这方面的指导，请您以您当地海关要求为准。若有不明白之处，请务必联系您当地海关咨询，特别是物品数量、单位、金额的填写，不同的地区可能有不同的要求，请以您当地海关的要求为准。</p>
        <p>EMS 自缴税订单，在包裹内放有一张准确的购物凭据（购物明细书），多数情况下不需要您自己申报，但确也有少数地区海关喜欢让收件人再申报一遍（顺丰含税包邮无此凭据提供）。</p>

        <h5 class="faq-subtitle">2、购买有金额和数量限制么</h5>
        <p>单次购买非单件商品金额上限是 2000 人民币（海关汇率非下单当日汇率，大额购买请务必提前了解规则），如果一个包裹内是多件可分开销售的商品，且价值超过 2000 人民币将被中国大陆海关退运（单件不可分的商品超额可通关）。</p>
        <p>因个别地区可能不认可价格排除其它费用，如果您完全不了解您当地海关情况，建议商品价格不超过 1500 人民币最为稳妥。</p>
        <p>包裹到达中国国内后，中国国内运输包裹内香烟、加热烟、雪茄合计不允许超过 400 支、烟丝不允许超过 5kg（请阅读完本章节！存在特殊情况！），包裹内可以同时包含香烟、加热烟、雪茄、烟丝。</p>
        <p>故单次下单须同时满足本站购物车校验：<strong>香烟、加热烟</strong>合计请勿超过 <strong>400 支</strong>（按商品所填每包/条支数累加），<strong>香烟</strong>合计请勿超过 <strong>20 盒/包</strong>，<strong>手卷烟丝</strong>合计请勿超过 <strong>5kg</strong>。雪茄若上架，亦计入上述 400 支限额。烟丝数量较多（特别是所谓的「拉满」）依旧存在被海关认定非「合理自用」的风险。</p>
        <p>EMS 自缴税订单结算时，先合计商品净重，再<strong>整单额外计入 100g 包装重</strong>（箱子、泡沫等）作为计费重量匹配运费档位，计费重量上限 16kg。</p>
        <p>以上是中国大陆总体层面的相关规定，但烟丝如果您当地海关对规定有本地特殊解读（例如烟丝限 500g、1000g，或烟丝需换算成烟支与烟支共享限额），您需要以您当地海关的地方性要求为准。</p>
        <p>中国大陆海关对加热烟的管理同香烟，但部分地区海关工作人员没见过加热烟，容易误判为液态雾化电子烟而拒绝放行，遇此情况您需要主动向海关申诉，怕麻烦请勿购买。</p>

        <h5 class="faq-subtitle">3、可以短期内多次购买么</h5>
        <p>频繁购买本网站可以为顾客发货，但中国大陆海关要求收件人购买的数量必须在「合理自用」范围内，且判断标准由各地海关自行掌握。</p>
        <p>建议顾客多在社交媒体上了解所在地区别人分享经验后再决定购买频率，或者采取保守策略等待第 1 次购买的商品收到后再第 2 次购买，以避免被您当地海关退运。如果退运不支持退款，重新邮寄需自行承担退运产生的费用（相关说明详见 <a href="{{ url('/pages/change-exchange-return.html') }}">退款章节</a>）。</p>

        <h5 class="faq-subtitle">4、如何缴税？是否包税？</h5>
        <p>本店目前上架的所有商品，除明确标注含税的以外，报价不包括收件人当地海关收取的税费。商品分类标明 EMS 的，采用国际 EMS 寄送，通过 EMS 寄送跨国包裹时中国大陆海关收取的税费需要收件人自行实名缴纳。</p>
        <p>包裹在到达中国国内后，海关、邮政分别会向收件人发送短信，届时收件人可按收到的短信指引缴纳税费（邮政渠道缴税据说有额外费用）。购买时请务必真实填写姓名与手机号，跨国包裹收件人姓名使用假名会导致包裹退运/丢失/销毁、无法顺利向海关缴纳税费等后果。如果收件人相关信息填写有误，请在发货前及时通过 <a href="{{ route('support.feedbacks.create') }}">客户反馈</a> 联系本站；待处理阶段且尚未开始处理时也可在订单内自助改址（最多 2 次），EMS 发货后无法再修改包裹的收件人信息。</p>
        <p>在日本，确实另有一些非 EMS 的物流的业务范围提供「包税」服务，但此类物流每天能承接的烟草商品包裹数量非常有限。店内不定期会提供特定烟草商品的顺丰含税包税，您需要碰巧遇上才会看见此活动（遇到直接可下单），不可提前预约，无邮件通知。</p>

        <h4 class="faq-section-title">三、关于赏味期限、生产日期</h4>
        <p>本店能够保证出售的所有商品赏味期限符合日本国内销售的要求。本店每周都会有 2、3 批新货送来，但每次烟草公司送来的货并不是肯定比上次新（例如赏味期限上次到货 26 年 12 月，下次到货也可能 26 年 09 月）。</p>
        <p>供货周转较快，一般不会长期滞留老旧库存；热门规格可能需要下单后等待新到货，请放心购买。</p>
        <p>另请注意，只有部分日本本土品牌才会在包装上标注赏味期限，国外品牌不会标注赏味期限、生产日期。部分国外品牌商品包装上印有编码但不含日期信息（碰巧包含小于等于 26 的数字那不是年份），不要轻信网传的各种说法（包括 AI 一本正经瞎编的说法）。有些包装撕开后接缝或者夹层有日期，但那只是印刷厂生产包装材料的日期，该日期经常比商品真实生产日期早 1、2 年甚至更久，没有参考价值。</p>

        <h4 class="faq-section-title">四、关于包装、印刷、口味不对</h4>
        <p>首先，本店所售烟草商品由日本烟草公司统一供货，所售全部都是真货、正品。</p>
        <p>但日本国内销售的品种，与日本免税店、中国免税店销售的品种，在口味上与包装印刷是有细微区别的，因为商品面向的消费人群不同。</p>
        <p>即便同样是日本国内销售的烟，不同批次也可能存在口感与包装的差异，请不要因为几年前抽过但这次味道变了、包装变了而怀疑烟的真假。</p>
        <p>众所周知，在中国，即便是同一款烟，生产企业也会在数年间多次微调配方与包装，这方面情况日本其实也是一样的，所以只有同一批次的口味、包装才有可比性。</p>
        <p>而且抽烟时自身的心境、身体情况都会影响到自己对一款烟的体验，例如鼻炎或感冒，即便康复后，很长一段时间都会影响自己的味觉。</p>
        <p>假烟可能在中国很普遍，但在日本是很罕见的，像本店这种在烟草公司进货后从日本直邮给您，完全不用担心真假问题，认准正规渠道购买，远比学习一大堆网络流传的所谓鉴别方法更有保障。</p>
        <p>但如果您依旧还是不放心，请一定不要在本店下单购买，购买收货后疑神疑鬼希望本店自证真伪，我们会感到被冒犯。</p>

